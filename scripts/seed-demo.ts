/**
 * 演示数据：造一本有内容的小说，用于验证界面与关系图
 *
 * 用法：node scripts/seed-demo.ts [目标工作区]
 */

import path from 'node:path';
import { promises as fs } from 'node:fs';
import { Workspace } from '@loom/core';

const root = path.resolve(process.argv[2] ?? path.join(process.cwd(), '.workspace'));

async function main(): Promise<void> {
  const ws = new Workspace(root);
  await ws.init('我的小说工作区');

  const existing = await ws.list();
  const found = existing.find((p) => p.name === '归墟纪');
  const project = found ?? (await ws.create({
    name: '归墟纪',
    description: '境界靠被记住程度决定的世界',
    packs: ['xianxia'],
  }));

  const engine = (await ws.engine(project.id))!;
  await ws.activate(project.id);

  const write = async (
    title: string,
    type: string | null,
    folder: string,
    fm: Record<string, unknown>,
    body: string,
  ) => {
    const existingNote = await engine.note(`${folder}/${title}.md`);
    if (existingNote) {
      await engine.updateNote(`${folder}/${title}.md`, { frontmatter: fm, body });
      return `${folder}/${title}.md`;
    }
    const r = await engine.createNote({ title, type, folder, frontmatter: fm, body });
    return r.path;
  };

  // ── 设定：修炼体系与境界 ──────────────────────────────
  await write('天地本源之力', '_concept', '06-设定', {
    name: '天地本源之力',
    description: '世界的底层能量。不同区域叫法不同，性质也可能不同。',
    aliases: [
      { name: '灵气', region: '东域', nature: '温和，可吸纳' },
      { name: '源力', region: '西荒', nature: '暴烈，需炼化', conflict: true },
      { name: '星尘', region: '天外', nature: '稀薄，只在天外可见' },
    ],
  }, [
    '# 天地本源之力',
    '',
    '万物皆由此出。但同一股力量，走到不同的地方，会换一个名字，也换一副脾气。',
    '',
    '- 东域称之为**灵气**，温和，可吸纳，修士赖之修行。',
    '- 西荒称之为**源力**，暴烈，需炼化，炼不好会走火入魔。',
    '- 天外称之为**星尘**，稀薄，只在天外可见。',
    '',
    '> [!clue]- 冲突提示',
    '> 灵气体系修士进入西荒，会受到源力压制 —— 这是本书前半段最重要的地理约束。',
  ].join('\n'));

  await write('归墟纪体系', '修炼体系', '06-设定', {
    order: 1,
  }, [
    '# 归墟纪体系',
    '',
    '本书主修炼体系。九个境界，从凡入神。',
    '',
    '境界不是力量，是**被记住的程度** —— 记住你的人越多，你在这个世界就越"实"。',
  ].join('\n'));

  const realms = [
    ['凡身', 1, '无人在意。寿七十。'],
    ['具名', 2, '一城传诵。寿一百二十。可立誓、可诅咒。'],
    ['显名', 3, '一国之志。寿二百。名号可入典籍。'],
    ['传世', 4, '千载之后仍有人念。寿五百。'],
    ['不朽', 5, '名与天地同寿。'],
  ] as const;

  for (const [name, order, desc] of realms) {
    await write(name, '境界', '06-设定', {
      order,
      parent: '归墟纪体系',
      scope: { space: '东域', time: '当今' },
    }, [
      `# ${name}`,
      '',
      desc,
      '',
      `属于[[归墟纪体系]]。`,
    ].join('\n'));
  }

  // 宇宙篇的并行体系（作用域隔离）
  await write('宇宙修炼', '修炼体系', '06-设定', {
    order: 2,
    scope: { space: '宇宙', time: '宇宙历' },
  }, [
    '# 宇宙修炼',
    '',
    '地球篇之后才展开的体系。与[[归墟纪体系]]**并行**，但作用域不重叠。',
  ].join('\n'));

  await write('行星级', '境界', '06-设定', {
    order: 10,
    parent: '宇宙修炼',
    scope: { space: '宇宙', time: '宇宙历' },
  }, [
    '# 行星级',
    '',
    '宇宙修炼的第一阶。能撕裂行星表面。',
    '',
    '在[[东域]]不存在这个境界 —— 这是作用域隔离的意义。',
  ].join('\n'));

  await write('武者', '境界', '06-设定', {
    order: 1,
    parent: '宇宙修炼',
    scope: { space: '地球', time: '21世纪' },
  }, [
    '# 武者',
    '',
    '地球篇的凡人武力。与[[行星级]]是**串行**关系 —— 时代切换后旧端失效。',
  ].join('\n'));

  // ── 人物 ────────────────────────────────────────────
  await write('沈砚', '人物', '05-人物', {
    age: 27,
    faction: '云隐宗',
    paths: [
      { system: '归墟纪体系', tier: '具名', order: 2 },
      { system: '炼体', tier: '铜皮', order: 1 },
    ],
    scope: { space: '东域', time: '当今' },
    relations: [
      { to: '苏挽', kind: '情感', note: '互为锚点', mutual: true },
      { to: '陆沉舟', kind: '师徒', mutual: true },
    ],
  }, [
    '# 沈砚',
    '',
    '二十七岁，眉骨有一道旧疤。左手无名指少一截。',
    '',
    '他记得所有人的名字，唯独忘了自己是谁。',
    '',
    '## 外貌',
    '',
    '常年一身洗旧的青灰短打。腰间挂一枚无字木牌 —— 那是他唯一带在身上的旧物。',
    '',
    '## 关键设定',
    '',
    '他的"具名"不是自己挣来的，是[[苏挽]]一遍遍叫他，把他叫住了。',
    '',
    '> [!clue] 伏笔',
    '> 无字木牌上原本有字，被磨掉了。磨掉的人是他自己。',
  ].join('\n'));

  await write('苏挽', '人物', '05-人物', {
    age: 24,
    faction: '云隐宗',
    paths: [{ system: '归墟纪体系', tier: '显名', order: 3 }],
    scope: { space: '东域', time: '当今' },
  }, [
    '# 苏挽',
    '',
    '云隐宗记名弟子。她记得所有人的名字，包括[[沈砚]]的。',
    '',
    '## 关系',
    '',
    '与沈砚互为锚点 —— 她叫他，他就还在。',
  ].join('\n'));

  await write('陆沉舟', '人物', '05-人物', {
    age: 61,
    faction: '云隐宗',
    paths: [{ system: '归墟纪体系', tier: '传世', order: 4 }],
    scope: { space: '东域', time: '当今' },
  }, [
    '# 陆沉舟',
    '',
    '云隐宗长老。沈砚的师父。',
    '',
    '他年轻时也丢过一次名字，找回来了，但代价是忘了另一个人的。',
  ].join('\n'));

  // ── 大纲 ────────────────────────────────────────────
  await write('全书大纲', '大纲', '01-大纲', {}, [
    '# 全书大纲',
    '',
    '## 一句话',
    '',
    '一个被世界遗忘的人，靠另一个人一遍遍叫他，重新变得"存在"。',
    '',
    '## 三幕',
    '',
    '1. **第一幕 · 无名**：沈砚在东域醒来，只记得自己叫沈砚。',
    '2. **第二幕 · 缄默**：他发现"境界"不是力量，是被记住的程度。有人正在系统性抹去一批人的名字。',
    '3. **第三幕 · 归墟**：他找到抹名的源头 —— 是他自己。',
    '',
    '## 分卷',
    '',
    '- [[卷一·初见]]',
    '- [[卷二·缄默]]',
  ].join('\n'));

  await write('卷一·初见', '大纲', '01-大纲', { order: 1 }, [
    '# 卷一·初见',
    '',
    '目标：建立"名字即存在"的规则，让读者在不知情中接受它。',
    '',
    '转折：沈砚第一次被人叫错名字，身体开始变淡。',
    '',
    '收束：[[第1章-织机之下]]',
  ].join('\n'));

  // ── 章纲 ────────────────────────────────────────────
  await write('第1章-章纲', '章纲', '02-章纲', {
    chapter: 1,
    arc: '卷一·初见',
    advances: ['主线·真相'],
    features: ['沈砚', '苏挽'],
    plants: ['伏笔-无字木牌'],
  }, [
    '# 第1章 章纲',
    '',
    '## 本章要做什么',
    '',
    '- 让沈砚醒来，交代"他只记得自己叫沈砚"',
    '- 苏挽第一次叫他，读者看到他的反应（不是感动，是松一口气）',
    '- 埋下无字木牌',
    '',
    '## 不做什么',
    '',
    '- 不解释境界体系（留到第 3 章）',
    '- 不让陆沉舟出场（留到第 5 章）',
  ].join('\n'));

  // ── 章节 ────────────────────────────────────────────
  await write('第1章-织机之下', '章节', '03-章节', {
    chapter: 1,
    arc: '卷一·初见',
  }, [
    '# 第1章 织机之下',
    '',
    '沈砚醒来的时候，听见的是织机的声音。',
    '',
    '不是他熟悉的任何一种声音。木头与木头相互咬着，一下，又一下，像有人在很慢地数数。',
    '',
    '"沈砚。"',
    '',
    '有人叫他。',
    '',
    '他睁开眼。屋顶是旧的，梁上挂着一层薄灰。织机在窗边，没有人踩它，它自己在动。',
    '',
    '"沈砚。"',
    '',
    '又叫了一声。这次他听清了，是个女子的声音，很稳，像在确认一件已经确认过很多次的事。',
    '',
    '他坐起来。腰间有一块木牌，无字。',
    '',
    '他摸了一下，指腹在木面上蹭过 —— 那里本该有字的，被磨平了，磨得很干净，像被人反复摩挲过许多年。',
    '',
    '---',
    '',
    '[[苏挽]]端着一碗水进来，看见他坐着，脚步停了半拍。',
    '',
    '"你叫什么？"她问。',
    '',
    '沈砚张了张嘴。',
    '',
    '那一瞬间他忽然发现，自己并不是"记得"这个名字 —— 他是"刚刚被叫醒"的。',
    '',
    '"沈砚。"他说。',
    '',
    '苏挽点点头，把水递给他。',
    '',
    '"对。"',
    '',
    '她转身去关窗。窗外是[[东域]]的天，很蓝，蓝得有点像假的。',
    '',
    '她没有说的是：今天已经是她第七次问他叫什么了。',
    '',
    '> [!clue] 本章埋下的东西',
    '> 无字木牌 —— 字是被磨掉的，磨掉的人是他自己。',
  ].join('\n'));

  await write('第2章-第七次', '章节', '03-章节', {
    chapter: 2,
    arc: '卷一·初见',
  }, [
    '# 第2章 第七次',
    '',
    '这一天，苏挽问了七次。',
    '',
    '第一次是清晨。第二次是吃过粥之后。第三次她假装只是随口一问。',
    '',
    '到第六次的时候，沈砚终于问："你为什么一直问我叫什么？"',
    '',
    '苏挽没有立刻答。她把织机上的线头理直，才说：',
    '',
    '"因为你不问，就会忘。"',
    '',
    '---',
    '',
    '她告诉他，东域的人管这个叫[[具名]]。',
    '',
    '「名字不是标签。名字是别人记得你。」',
    '',
    '「一个人被记得越多，他在这里就越实在。反过来 —— 」',
    '',
    '她没有说下去。',
    '',
    '沈砚低头看了看自己的手。',
    '',
    '晨光从窗缝里进来，照在他左手无名指的位置。那里少了一截。',
    '',
    '他不记得是怎么少的。',
  ].join('\n'));

  // ── 线索 ────────────────────────────────────────────
  await write('主线·真相', '线索', '04-线索', {
    span: { from: 1, to: 300 },
    status: 'active',
  }, [
    '# 主线·真相',
    '',
    '谁在抹去名字？为什么？',
    '',
    '贯穿全书。答案是：[[沈砚]]自己。',
  ].join('\n'));

  await write('伏笔-无字木牌', '伏笔', '04-线索', {
    status: 'planted',
    plantedIn: '第1章-织机之下',
  }, [
    '# 伏笔-无字木牌',
    '',
    '第 1 章埋。',
    '',
    '木牌上原本刻着他的真名。他自己磨掉的。',
    '',
    '回收点：第三幕。',
  ].join('\n'));

  await write('支线·师徒', '线索', '04-线索', {
    span: { from: 5, to: 180 },
    status: 'active',
  }, [
    '# 支线·师徒',
    '',
    '[[陆沉舟]]与[[沈砚]]。',
    '',
    '陆沉舟年轻时也丢过一次名字 —— 他找回来了，代价是忘了另一个人。',
    '',
    '这条线在第 5 章启动。',
  ].join('\n'));

  // 刷新索引
  await engine.reindex();

  const st = await engine.stats();
  const check = await engine.check();

  console.log(`已就绪：${project.name}`);
  console.log(`  路径：${project.path}`);
  console.log(`  笔记 ${st.notes} 篇 · ${st.words} 字 · ${st.relations} 条关系`);
  console.log(`  类型 ${st.types} 个 · 概念 ${st.concepts} 个 · 未归类 ${st.untyped} 篇`);
  console.log(`  断链 ${check.broken.length} · 作用域冲突 ${check.scopeConflicts.length} · 概念冲突 ${check.conceptConflicts.length}`);
  console.log(`  项目 id：${project.id}`);

  await ws.releaseAll();
}

main().catch((err) => {
  console.error('造数据失败：', err);
  process.exit(1);
});
